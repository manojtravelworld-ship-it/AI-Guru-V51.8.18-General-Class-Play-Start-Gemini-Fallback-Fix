export type MathDomain =
  | 'arithmetic' | 'number_systems' | 'fractions' | 'decimals_percentages' | 'ratio_proportion'
  | 'algebra' | 'linear_equations' | 'inequalities' | 'polynomials' | 'sequences_series'
  | 'coordinate_geometry' | 'functions' | 'trigonometry' | 'geometry'
  | 'mensuration' | 'calculus' | 'statistics' | 'probability'
  | 'matrices' | 'vectors' | 'complex_numbers' | 'financial_math' | '3d_geometry' | 'sets' | 'combinatorics'
  | 'general';

export type MathVisualKind =
  | 'text' | 'latex' | 'line' | 'shape' | 'point' | 'arrow' | 'graph'
  | 'highlight' | 'transform' | 'erase' | 'token-move';

export interface MathVisualNode {
  id: string;
  kind: MathVisualKind;
  x?: number; y?: number; width?: number; height?: number;
  content?: string; latex?: string; shape?: 'rectangle'|'circle'|'triangle';
  startX?: number; startY?: number; endX?: number; endY?: number;
  radius?: number; targetId?: string; from?: string; to?: string;
  graph?: { x: number[]; y: number[]; labels?: string[]; title?: string };
  style?: Record<string, string|number>;
}

export interface MathVisualEvent {
  id: string;
  atMs: number;
  durationMs: number;
  kind: 'draw'|'move'|'transform'|'highlight'|'erase'|'pause'|'camera';
  targetId?: string;
  textCue?: string;
  /** Source/target identities allow the browser renderer to interpolate persistent objects. */
  fromObjectId?: string;
  toObjectId?: string;
  retainFrom?: boolean;
  fromX?: number;
  fromY?: number;
  toX?: number;
  toY?: number;
  camera?: { action: 'zoom'|'pan'|'focus'; x?: number; y?: number; scale?: number };
  /** Optional word-level timing generated by the lesson compiler; audio engines may replace these with measured timings. */
  cueWords?: Array<{ word: string; atMs: number }>;
  sourceBeatId?: string;
}

export interface SemanticVisualGraph {
  schemaVersion: '1.0';
  nodes: Array<{ id: string; objectId: string; kind: SemanticMathObjectKind; value?: string; visualNodeId?: string; role?: SemanticMathObject['role'] }>;
  edges: Array<{ id: string; from: string; to: string; relation: SemanticMathRelation['relation'] }>;
  roots: string[];
  constructionOrder: string[];
}

export interface VisualConstructionPlan {
  schemaVersion: '1.0';
  pass1: { graphNodeCount: number; graphEdgeCount: number };
  pass2: { stepIds: string[]; executable: boolean; warnings: string[] };
}

export interface UniversalMathStep {
  id: string;
  title: string;
  purpose: string;
  before: string;
  after: string;
  operation: string;
  explanationEnglish?: string;
  explanationMalayalam?: string;
  source?: 'mathsteps' | 'sympy' | 'mathjs' | 'gemini' | 'manual';
  verified: boolean;
  visualActions?: Array<{ type: 'token-move'; id: string; token: string; fromX: number; fromY: number; toX: number; toY: number; durationMs?: number; fadeOut?: boolean; fontSize?: number; visualStyleId?: string } | { type: string; targetId?: string; from?: string; to?: string }>;
  audioCueId?: string;
  sourceIds?: string[];
  sourcePage?: number;
}

export interface UniversalMathScene {
  schemaVersion: '1.0';
  id: string;
  domain: MathDomain;
  gradeBand: '1-5'|'6-8'|'9-10'|'11-12';
  title: string;
  expression: string;
  verified: boolean;
  verification?: { normalized?: string; steps?: string[]; errors: string[] };
  nodes: MathVisualNode[];
  events: MathVisualEvent[];
  /** Explicit executable micro-animations such as moving one digit/term independently. */
  visualActions?: Array<{ type: 'token-move'; id: string; token: string; fromX: number; fromY: number; toX: number; toY: number; durationMs?: number; fadeOut?: boolean; fontSize?: number; visualStyleId?: string }>;
  /** Exactly one narration/caption language is active for a render pass. */
  narrationCues: Array<{ id:string; atMs:number; language:'english'|'malayalam'; text:string; targetId?:string }>;
  /** Language used by this scene render. English is always the first teaching pass. */
  teachingLanguage: 'english'|'malayalam';
  visualLanguage?: { mode: VisualMathMode; principle: 'animate-the-mathematics'; referenceVideoUse: 'style-only'; forbiddenTechniqueTransfer: string[] };
  semanticVisualPlan?: SemanticVisualPlan;
  semanticGraph?: SemanticVisualGraph;
  constructionPlan?: VisualConstructionPlan;
  visualStyle?: { id: string; name: string; score: number; reasons: string[]; alternatives: string[]; referenceIds?: string[]; referenceUrls?: string[]; commonTeachingStyleId?: string; qaProfileId?: string; referenceSegmentId?: string; referenceSegmentAsset?: string; referenceSegmentStartMs?: number; referenceSegmentEndMs?: number };
}

export type VisualMathMode = 'construction' | 'transformation' | 'hybrid';

export type SemanticMathObjectKind =
  | 'number' | 'digit' | 'operator' | 'term' | 'equation' | 'fraction'
  | 'point' | 'line' | 'angle' | 'shape' | 'graph' | 'matrix-cell' | 'vector'
  | 'label' | 'result';

export interface SemanticMathObject {
  id: string;
  kind: SemanticMathObjectKind;
  value?: string;
  visualNodeId?: string;
  role?: 'given' | 'operation' | 'intermediate' | 'result' | 'context';
}

export interface SemanticMathRelation {
  id: string;
  from: string;
  to: string;
  relation: 'contains' | 'equals' | 'balances' | 'operates-on' | 'moves-to' | 'derived-from' | 'highlights';
}

export interface VisualConstructionStep {
  id: string;
  narrationKey: string;
  actions: Array<
    | { type: 'create'; objectId: string }
    | { type: 'highlight'; objectId: string }
    | { type: 'move'; objectId: string; toX: number; toY: number }
    | { type: 'transform'; fromObjectId: string; toObjectId: string }
    | { type: 'erase'; objectId: string }
    | { type: 'pause'; durationMs: number }
  >;
}

export interface SemanticVisualPlan {
  objects: SemanticMathObject[];
  relations: SemanticMathRelation[];
  steps: VisualConstructionStep[];
}

export interface UniversalMathCompileOptions {
  preferredStyle?: string;
  /** Render one language at a time. English is the first pass; Malayalam is the translation pass. */
  language?: 'english'|'malayalam';
  bilingual?: boolean;
  id?: string;
  grade?: number;
  domain?: MathDomain;
  durationMs?: number;
  verify?: boolean;
  visualMode?: VisualMathMode;
}
