import { executeAIGuruAgent } from '../runtime/execute-agent';

/** Connects the new multi-agent contracts to the existing v43 Gemini lesson generator. */
export function createV43TeachingController() {
  return new TeachingController({
    lesson: new LessonAgent(async ({ lesson }: { lesson: Lesson }) => {
      const paragraphs: Paragraph[] = [];
      for (const paragraph of lesson.paragraphs) {
        const source: ParagraphSource = {
          bookId: paragraph.source.bookId,
          chapterIndex: 0,
          paragraphIndex: paragraph.index,
          pageNumber: paragraph.source.pageNumber,
          text: paragraph.source.text,
          pageImage: String(paragraph.source.pageImage),
          boundingBox: paragraph.source.boundingBox,
        };
        const plan = await generateTeachingPlan(source);
        paragraphs.push({
          ...paragraph,
          teachingIntent: 'Teach and explain the supplied textbook paragraph clearly.',
          explanation: { english: plan.english.text, malayalam: plan.malayalam.text },
          visualSteps: plan.english.visuals.map((action: any, i: number) => ({
            id: ids.visualStep(paragraph.id, i),
            paragraphId: paragraph.id,
            order: i,
            purpose: 'Generated by existing v43 Gemini teaching planner',
            action,
          })),
          audioCues: plan.cues.map((cue: any, i: number) => ({
            id: ids.audioCue(paragraph.id, i),
            paragraphId: paragraph.id,
            language: cue.track,
            trigger: cue.trigger,
            triggerText: cue.triggerText,
            startMs: cue.startMs,
            endMs: cue.endMs,
          })),
        });
      }
      return { ...lesson, paragraphs };
    }),
  });
}

export async function runV43TeachingPipeline(legacyLesson: AIGuruLesson) {
  const canonical = legacyLessonToCanonical(legacyLesson);
  const controller = createV43TeachingController();
  await recordAIGuruAudit({type:'pipeline_started',agent:'teaching-controller',runId:undefined,lessonId:canonical.id,status:'STARTED'});
  const result = await controller.buildLesson(canonical);
  await recordAIGuruAudit({type:'content_lesson_pipeline',agent:'teaching-controller',runId:result.runId,lessonId:canonical.id,status:result.status,data:{contentQA:result.contentQA.status,lessonQA:result.lessonQA.status}});
  if (result.status !== 'passed') {
    return { ...result, math: undefined, mathFailures: [], visualQA: undefined, visualParagraphQA: [], visualRecoveryAttempts: 0, lesson: canonicalLessonToLegacy(result.lesson, legacyLesson) };
  }
  // Sprint 4: math is verified and compiled per paragraph before visual QA.
  // The existing mathjs/mathsteps verifier and Universal Math Compiler are reused.
  const mathAgent = new MathAgent(new MathJsMathstepsVerifier());
  const math = await executeAIGuruAgent(mathAgent,{
    agent: 'math',
    context: { runId: result.runId, lessonId: result.lesson.id },
    input: { lesson: result.lesson },
  });
  if (!math.ok || !math.output) throw new Error(math.error?.message ?? 'Math agent failed');
  const mathLesson = {
    ...math.output.lesson,
    paragraphs: math.output.lesson.paragraphs.map(paragraph => {
      const compiled = mathScenesToVisualActions(paragraph);
      if (!compiled.length) return paragraph;
      const existing = new Set(paragraph.visualSteps.map(step => String(step.id)));
      const additions = compiled.filter(action => !existing.has(String(action.id))).map((action, index) => ({
        id: ids.visualStep(paragraph.id, paragraph.visualSteps.length + index),
        paragraphId: paragraph.id,
        order: paragraph.visualSteps.length + index,
        purpose: 'Verified mathematics compiled by the Universal Math Visual Compiler',
        action,
      }));
      return { ...paragraph, visualSteps: [...paragraph.visualSteps, ...additions], qa: { ...paragraph.qa, visual: 'pending' as const } };
    }),
  };
  const mathFailures = mathLesson.paragraphs.flatMap(p => (p.math?.failures ?? []).map(message => ({ paragraphId: p.id, message })));
  if (mathFailures.length) {
    return { ...result, math, mathFailures, visualQA: undefined, visualParagraphQA: [], visualRecoveryAttempts: 0, lesson: canonicalLessonToLegacy(mathLesson, legacyLesson), status: 'blocked' as const };
  }
  await recordAIGuruAudit({type:'math_completed',agent:'math',runId:result.runId,lessonId:mathLesson.id,status:mathFailures.length?'FAIL':'PASS',data:{failureCount:mathFailures.length}});
  const visual = await runVisualStepPipeline(mathLesson);
  if (visual.status !== 'passed') {
    return { ...result, visualQA: visual.visualQA, visualParagraphQA: visual.paragraphQA, visualRecoveryAttempts: visual.recoveryAttempts, math, mathFailures: [], status: 'blocked' as const, lesson: canonicalLessonToLegacy(visual.lesson, legacyLesson) };
  }
  // Sprint 5: voice/cue synchronization and final classroom integrity QA.
  // No duration-based visual timing is fabricated; real word boundaries may be supplied later.
  await recordAIGuruAudit({type:'visual_qa_completed',agent:'visual-step',runId:result.runId,lessonId:visual.lesson.id,status:visual.status,data:{paragraphs:visual.paragraphQA.length,recoveryAttempts:visual.recoveryAttempts}});
  const voice = await runVoiceSyncClassroomPipeline(visual.lesson);
  await recordAIGuruAudit({type:'classroom_qa_completed',agent:'teaching-controller',runId:result.runId,lessonId:visual.lesson.id,status:voice.status,data:{classroomQA:voice.classroomQA?.status ?? 'unknown'}});
  const modelRouter = new ModelRouterAgent();
  const routes = await Promise.all((['lesson','math','visual','voice'] as const).map(task => executeAIGuruAgent(modelRouter,{
    agent: 'model-router', context: { runId: result.runId, lessonId: visual.lesson.id }, input: { task }
  })));
  return {
    ...result,
    visualQA: visual.visualQA,
    visualParagraphQA: visual.paragraphQA,
    visualRecoveryAttempts: visual.recoveryAttempts,
    math,
    mathFailures: [],
    voice,
    classroomQA: voice.classroomQA,
    sync: voice.sync,
    modelRoutes: routes.map(r => r.output).filter(Boolean),
    status: voice.status,
    lesson: canonicalLessonToLegacy(voice.lesson, legacyLesson),
  };
}
