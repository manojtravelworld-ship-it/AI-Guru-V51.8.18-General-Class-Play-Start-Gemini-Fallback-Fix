import { generateTeachingPlan } from '../generation/gemini';
import { legacyLessonToCanonical, canonicalLessonToLegacy } from './legacy-adapter';
import { TeachingController } from '../agents/controller/teaching-controller';
import { LessonAgent } from '../agents/lesson/lesson-agent';
import { ids, type Lesson, type Paragraph } from '../contracts';
import { runVisualStepPipeline } from './sprint3-visual-pipeline';
import { MathAgent, mathScenesToVisualActions } from '../agents/math/math-agent';
import { MathJsMathstepsVerifier } from '../math/mathjs-mathsteps';
import { runVoiceSyncClassroomPipeline } from './sprint5-voice-pipeline';
import { ModelRouterAgent } from '../agents/model-router';
