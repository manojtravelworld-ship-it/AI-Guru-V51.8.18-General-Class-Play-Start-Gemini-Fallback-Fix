import type { MathDomain } from '../math/universal/types';

/** Renderer-neutral mathematical domain used by the AI Guru video compiler. */
export type GuruMathDomain = MathDomain;

export type GuruLanguage = 'english' | 'malayalam';

export type RendererKind = 'math-engine' | 'ltx' | 'composition';

export type SceneObjectSource = 'textbook' | 'math-engine' | 'ltx' | 'asset' | 'system';

export type VisualObjectKind =
  | 'text'
  | 'equation'
  | 'geometry'
  | 'graph'
  | 'point'
  | 'line'
  | 'shape'
  | 'image'
  | 'video'
  | 'highlight'
  | 'arrow'
  | 'caption';

export interface SceneAssetRef {
  id: string;
  uri: string;
  type: 'image' | 'video' | 'audio' | 'pdf-page' | 'data';
  source?: SceneObjectSource;
  page?: number;
  metadata?: Record<string, string | number | boolean>;
}

export interface ScenePoint {
  x: number;
  y: number;
}

export interface SceneRegion {
  x: number;
  y: number;
  width: number;
  height: number;
}

export interface CameraState {
  framing?: 'full' | 'medium' | 'close' | 'detail';
  x?: number;
  y?: number;
  scale?: number;
  rotation?: number;
}

export interface CameraIntent {
  id: string;
  atMs: number;
  durationMs: number;
  from?: CameraState;
  to?: CameraState;
  reason?: string;
}

export interface VisualObject {
  id: string;
  kind: VisualObjectKind;
  source: SceneObjectSource;
  content?: string;
  asset?: SceneAssetRef;
  region?: SceneRegion;
  position?: ScenePoint;
  zIndex?: number;
  persistent?: boolean;
  /** Links the object back to a verified mathematical object/step when applicable. */
  semanticRef?: string;
  /** Mathematical objects must never be generated by the generative renderer. */
  deterministic?: boolean;
  metadata?: Record<string, string | number | boolean>;
}

export type VisualAction =
  | { type: 'create'; objectId: string }
  | { type: 'draw'; objectId: string }
  | { type: 'transform'; fromObjectId: string; toObjectId: string }
  | { type: 'move'; objectId: string; to: ScenePoint }
  | { type: 'highlight'; objectId: string }
  | { type: 'erase'; objectId: string }
  | { type: 'camera'; cameraId: string }
  | { type: 'pause'; durationMs: number };

export interface TimelineCue {
  id: string;
  atMs: number;
  durationMs?: number;
  language?: GuruLanguage;
  text?: string;
  targetObjectIds?: string[];
  beatId?: string;
}

export interface AudioCue {
  id: string;
  atMs: number;
  durationMs?: number;
  language: GuruLanguage;
  text: string;
  word?: string;
  tokenIndex?: number;
  targetObjectIds?: string[];
}

export type GenerativeCondition =
  | { type: 'reference-image'; asset: SceneAssetRef; strength?: number }
  | { type: 'reference-video'; asset: SceneAssetRef; strength?: number; startMs?: number; endMs?: number }
  | { type: 'keyframe'; atMs: number; asset: SceneAssetRef }
  | { type: 'mask'; region: SceneRegion; targetObjectIds?: string[] }
  | { type: 'previous-state'; sceneId: string }
  | { type: 'text'; prompt: string };

export interface GenerativeVisualPlan {
  enabled: boolean;
  purpose: 'cinematic' | 'reference-animation' | 'transition' | 'background' | 'visual-metaphor';
  conditions: GenerativeCondition[];
  durationMs: number;
  /** The generative renderer may suggest imagery, but never owns verified mathematics. */
  forbiddenOutputs: Array<'equations' | 'graphs' | 'geometry-truth' | 'verified-labels' | 'mathematical-transformations'>;
}

export interface RendererPolicy {
  math: {
    renderer: 'math-engine';
    deterministic: true;
  };
  generative: {
    renderer: 'ltx' | 'none';
    enabled: boolean;
    deterministic: false;
  };
  composition: {
    renderer: 'composition';
    deterministic: true;
  };
}

export interface CompositionLayer {
  id: string;
  source: 'textbook' | 'math-engine' | 'ltx' | 'audio' | 'caption' | 'system';
  objectIds?: string[];
  assetIds?: string[];
  startMs: number;
  endMs: number;
  zIndex: number;
  opacity?: number;
  blendMode?: string;
}

export interface SceneKeyframe {
  id: string;
  atMs: number;
  state: string;
  objectIds: string[];
  narrationCueId?: string;
}

export interface GuruScene {
  schemaVersion: '1.0';
  id: string;
  lessonId: string;
  segmentId: string;
  beatId?: string;
  title: string;
  domain: GuruMathDomain;
  grade: number;
  gradeBand: '1-5' | '6-8' | '9-10' | '11-12';
  language: GuruLanguage;

  durationMs: number;
  teachingGoal: string;

  objects: VisualObject[];
  actions: VisualAction[];
  cameras: CameraIntent[];
  keyframes: SceneKeyframe[];
  timelineCues: TimelineCue[];
  audioCues: AudioCue[];

  generative: GenerativeVisualPlan;
  layers: CompositionLayer[];
  rendererPolicy: RendererPolicy;

  /** IDs of certified/verified mathematical sources used by this scene. */
  verificationRefs: string[];
  metadata?: Record<string, string | number | boolean>;
}

export interface GuruLesson {
  schemaVersion: '1.0';
  id: string;
  title: string;
  grade: number;
  gradeBand: GuruScene['gradeBand'];
  domain: GuruMathDomain;
  language: GuruLanguage;
  scenes: GuruScene[];
  totalDurationMs: number;
  metadata?: Record<string, string | number | boolean>;
}

export interface SceneCompilerInput {
  lessonId: string;
  lessonTitle: string;
  grade: number;
  gradeBand: GuruScene['gradeBand'];
  domain: GuruMathDomain;
  language: GuruLanguage;
  teachingGoal: string;
  segmentId: string;
  segmentTitle: string;
  beatId: string;
  narration: string;
  durationMs: number;
  cueWords?: string[];
  targetObjects?: string[];
  actions?: VisualAction[];
  mathObjectIds?: string[];
  textbook?: SceneAssetRef;
  references?: SceneAssetRef[];
  verificationRefs?: string[];
  generative?: Partial<GenerativeVisualPlan>;
}
